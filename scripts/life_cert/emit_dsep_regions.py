"""Emit `DecSepThr2.lean`: the run and rest regions of the `decJz` registers are far from every piece
of the machine other than the circuit (untrusted generator; Lean checks every statement).

For every region list `L` of `decRunRegNZ`, `decRunRegZ`, `decRestRegNZ`, `dz2mk0RestRegion`:
`dsepT_<L>_zone` (the components lie in the zone `dsepTZone`), `dsepT_<L>_cls` (far from every
class of piece of the module other than the groups, and for the rest of the zero test the INC
gate) and `dsepT_<L>_far` (far from every piece of the machine outside the circuit).

Usage: emit_dsep_regions.py OUT.lean"""

#!/usr/bin/env python3
"""Extended capture certificates of the `decJz` step (untrusted generator; Lean checks everything).

After the capture at a station (`stCaptureNZ_relay`, 492 generations; `stCaptureZ_relay`, 472) the
dispatched answer is still within distance 2 of the station's boxes for about 96 generations.  These
certificates run the station and the dispatched answer together for `E = 200` more generations
(`stCaptureNZ_ext`, `stCaptureZ_ext`), after which the answer is past its station (`u <= U - 553`
for NZ, `v >= 710` for Z, module frame).

Usage: cap_ext.py OUT.lean"""
import os
import re
import sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'life_gates'))
from life import step_cells, window_of_cells, cells_of_window  # noqa: E402

LT = os.path.join(HERE, '..', '..', 'LeanTheory', 'Theory', 'Life')
E = 200


def lean_rows(src, name):
    m = re.search(r"def " + name + r" : Finset Cell :=\s*ofRows \(?(-?\d+)\)? \(?(-?\d+)\)?\s*\[([\d,\s]*)\]",
                  src)
    return cells_of_window(int(m.group(1)), int(m.group(2)),
                           [int(x) for x in m.group(3).split(',') if x.strip()])


def ev(c, n):
    for _ in range(n):
        c = step_cells(c)
    return c


def run_hull(c, n):
    def bb(c):
        xs = [a for a, _ in c]
        ys = [b for _, b in c]
        return (min(xs), max(xs), min(ys), max(ys))
    h = bb(c)
    for _ in range(n):
        c = step_cells(c)
        b = bb(c)
        h = (min(h[0], b[0]), max(h[1], b[1]), min(h[2], b[2]), max(h[3], b[3]))
    return c, h


def z(v):
    return '(%d)' % v if v < 0 else str(v)


def ofr(c):
    x, y, rows = window_of_cells(c)
    return 'ofRows %s %s [%s]' % (z(x), z(y), ', '.join(map(str, rows)))


def pad(A, U):
    x, y, _ = window_of_cells(A)
    X, Y, _ = window_of_cells(U)
    return "ofRows_eq_padRows' %s %s %s %s %d %d _ (by norm_num) (by norm_num)" % (
        z(X), z(Y), z(x), z(y), y - Y, x - X)


def boxs(b):
    return 'Box %s %s %s %s' % (z(b[0]), z(b[1]), z(b[2]), z(b[3]))


HDR = '''/-
Copyright (c) 2026 LeanTheory contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: LeanTheory contributors
-/
module

public import LeanTheory.Theory.Life.StationFacts

/-!
# Generated: the captures at the stations, extended by %d generations

Generated by `scripts/life_cert/cap_ext.py` (untrusted; every certificate is checked here). After
the capture (`stCaptureNZ_relay`, `stCaptureZ_relay`) the dispatched answer is still close to the
station; the station and the answer run together for `%d` more generations
(`stCaptureNZ_ext`, `stCaptureZ_ext`), after which the answer is clear of the station.
-/

@[expose] public section

namespace LeanTheory.Life

open Finset

set_option linter.style.longLine false
''' % (E, E)


def main(out):
    src = open(os.path.join(LT, 'StationFacts.lean')).read()
    parts = [HDR]
    for nm, n0 in (('NZ', 492), ('Z', 472)):
        gname = 'stCapture%sG' % nm
        G = lean_rows(src, gname)
        Out = lean_rows(src, 'stCapture%sOut' % nm)
        G0 = ev(G, n0 % 30)
        G1 = ev(G, (n0 + E) % 30)
        end, h = run_hull(G0 | Out, E)
        # the answer moves `E / 4` cells along its direction
        cand = None
        for dx in (-1, 1):
            for dy in (-1, 1):
                O2 = {(x + dx * E // 4, y + dy * E // 4) for (x, y) in Out}
                if end == G1 | O2:
                    cand = O2
        assert cand is not None, nm
        U0 = G0 | Out
        U1 = G1 | cand
        parts.append('''
/-- The pieces of `capture_%s` after %d generations. -/
theorem stCapture%sG_phase%d : phase stCapture%sG %d = %s := by
  rw [phase, show %d %% 30 = %d by norm_num, stCapture%sG]
  life_cert

/-- The output of `capture_%s`, %d generations later. -/
def stCapture%sOutE : Finset Cell := %s

set_option maxRecDepth 100000 in
/-- **Certificate**: the station and the dispatched answer of `capture_%s`, %d more generations,
inside `%s`. -/
theorem stCapture%s_ext :
    Reaction (phase stCapture%sG %d ∪ stCapture%sOut) (phase stCapture%sG %d ∪ stCapture%sOutE) %d
      (fun _ => %s) := by
  rw [stCapture%sG_phase, stCapture%sG_phase%d,
    show (%s ∪ stCapture%sOut : Finset Cell) = %s by
      rw [stCapture%sOut, %s, %s, ← ofRows_orRows]; rfl,
    show (%s ∪ stCapture%sOutE : Finset Cell) = %s by
      rw [stCapture%sOutE, %s, %s, ← ofRows_orRows]; rfl]
  life_reaction
''' % (nm, n0 + E, nm, n0 + E, nm, n0 + E, ofr(G1), n0 + E, (n0 + E) % 30, nm,
       nm, E, nm, ofr(cand),
       nm, E, boxs(h),
       nm, nm, n0, nm, nm, n0 + E, nm, E, boxs(h),
       nm, nm, n0 + E,
       ofr(G0), nm, ofr(U0), nm, pad(G0, U0), pad(Out, U0),
       ofr(G1), nm, ofr(U1), nm, pad(G1, U1), pad(cand, U1)))
    parts.append('\nend LeanTheory.Life\n')
    open(out, 'w').write(''.join(parts))


if __name__ == '__main__':
    main(sys.argv[1])

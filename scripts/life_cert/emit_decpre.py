#!/usr/bin/env python3
"""Emit `Gen/DecPreOps.lean`: the decJz register runs up to their cut inside the prefix regions.

For every split run `X` (`dz2dOpS` ... `dz2d3OpS`, `dz2mk0Run_restS` ... `dz2mk7Run_restS`) the
first part of the split statement (the run up to the cut, footprint `XRegion`) is restated with
the footprint `XPreRegion` of `Gen/<X>PreG.lean`: the prefix run `XPreS` and the prefix region
run `XPreG` start from the same configuration and have the same length, so the footprint of the
latter can be used (`Reaction.refoot`); the start is rewritten as in the split file (the proof
of `hs` is copied).  Untrusted generator: Lean checks every statement.

Usage: emit_decpre.py OUT.lean
"""
import os
import re
import sys

GEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'LeanTheory', 'Theory',
                   'Life', 'Gen')
RUNS = [('dz2d', 'Dz2dSplit', 'dz2dOpS'), ('dz2d1', 'Dz2d1Split', 'dz2d1OpS'),
        ('dz2d2', 'Dz2d2Split', 'dz2d2OpS'), ('dz2d3', 'Dz2d3Split', 'dz2d3OpS')] + \
    [('dz2mk%d' % k, 'Dz2mk%dSplit' % k, 'dz2mk%dRun_restS' % k) for k in range(8)]

HDR = '''/-
Copyright (c) 2026 LeanTheory contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: LeanTheory contributors
-/
module

%s

/-!
# Generated: the decJz register runs up to their cut, inside the prefix regions

Generated by `scripts/life_cert/emit_decpre.py` (untrusted; Lean checks every step). For every
split run of the `decJz` activation, the run up to the cut (the first part of `<p>OpS` /
`<p>Run_restS`) stays in the region `<p>PreRegion` of the prefix run (`Gen/<P>PreG`), which does
not contain the later flight of the answer.
-/

@[expose] public section

namespace LeanTheory.Life

open Finset

set_option linter.style.longLine false
set_option linter.unusedSimpArgs false

/-- **Two reactions from the same configuration, of the same length**: the result of the first
with the footprint of the second. -/
theorem Reaction.refoot {P Q Q' : Finset Cell} {n : ℕ} {F G : ℕ → Set Cell}
    (h : Reaction P Q n F) (h' : Reaction P Q' n G) : Reaction P Q n G :=
  ⟨h.evolve_eq, h'.subset⟩
'''


def main(out):
    imports = []
    body = []
    for (p, split, opname) in RUNS:
        P = p[0].upper() + p[1:]
        imports += ['public import LeanTheory.Theory.Life.Gen.%s' % split,
                    'public import LeanTheory.Theory.Life.Gen.%sPreG' % P]
        src = open(os.path.join(GEN, split + '.lean')).read()
        i = src.index('theorem %s ' % opname) if ('theorem %s ' % opname) in src else \
            src.index('theorem %s\n' % opname)
        i2 = src.index('theorem %s' % opname)
        j = src.index(':= by', i2)
        sig = src[i2:j]
        m = re.match(r'theorem \S+(.*?)    Reaction (.*?)\n\s*\(fun _ => %sRegion\) ∧' % p, sig, re.S)
        if m is None:
            m = re.match(r'theorem \S+(.*?):\n    Reaction (.*?)\n\s*\(fun _ => %sRegion\) ∧' % p, sig, re.S)
        args, reac = m.group(1), m.group(2)
        args = args.rstrip()
        if args.endswith(':'):
            args = args[:-1].rstrip()
        k = src.index('  have hs :', j)
        k2 = src.index('  have eY', k)
        hs = src[k:k2]
        # argument names for the applications
        pre_args = " q K Vs Vb Vs' m0 hv hv' hm hVb hVs hVs'" if args.strip() else ''
        g_args = pre_args
        body.append('''
set_option maxRecDepth 100000 in
/-- **The run `%s` up to its cut** inside the prefix region `%sPreRegion`. -/
theorem %sOpP%s :
    Reaction %s
      (fun _ => %sPreRegion) := by
%s  exact (Reaction.refoot (%sPreS%s) (%sPreG%s)).congrPQ hs rfl
''' % (p, p, p, (' ' + args.strip()) if args.strip() else '', reac.strip(), p, hs, p, pre_args, p,
       g_args))
    with open(out, 'w') as f:
        f.write(HDR % '\n'.join(imports))
        f.write(''.join(body))
        f.write('\nend LeanTheory.Life\n')


if __name__ == '__main__':
    main(sys.argv[1])

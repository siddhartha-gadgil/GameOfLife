"""The 30 phases of the OR gate in a tight footprint (untrusted generator; Lean checks everything).

The OR gate (`orGate`, box `[0, 90] x [0, 32]`) has no live cell with `x >= 60` and `y >= 20` in
any phase: every phase lies in `Box 0 90 0 19 ∪ Box 0 59 0 32`.  For each phase `k < 30` the
generator emits `conway.evolve k orGate = ofRows 0 0 rows_k` (checked by `life_cert`), and the
rows are checked against the footprint by the Boolean checker `tightRowsOK` (Lean).

Usage: or_gate_tight.py OUT.lean"""
